
let day = "tuesday "

// To check the length of the string
let dayLength = day.length
console.log(dayLength)

// To get substring from a string
let subString = day.slice(0,4)
console.log(subString)

// To access a char of a string
let charString = day[1]
console.log(charString)

// To split of a string
let splitString = day.split("s")
console.log(splitString)

// To get only the first set of split string
console.log(splitString[1])

// To trim a space
console.log(day.trim())